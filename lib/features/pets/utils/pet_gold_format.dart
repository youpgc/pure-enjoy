/// 金币展示格式化（面向用户的货币单位转换）
///
/// 阈值口径：满 100K 切 K、满 1M 切 M（K 段整数部分恒为 3 位：100.0K~999.9K）；
/// 未达阈值一律原样展示（50,000 就是 50000，不写 50K）。
/// 小数位**截断不四舍五入**（999,999 → 999.9K，绝不进位成 1000.0K）。
library;

/// 是否已进入单位转换区间（达到阈值才可点开完整数额）
bool petGoldConverted(int v) => v >= 100000;

String petGoldLabel(int v) {
  if (v < 100000) return '$v';
  if (v < 1000000) return '${(v ~/ 100) / 10}K';
  return '${(v ~/ 100000) / 10}M';
}
